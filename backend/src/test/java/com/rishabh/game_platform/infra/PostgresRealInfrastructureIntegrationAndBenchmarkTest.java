    @Test
    @Order(1)
    @DisplayName(
        "PG-01: Verify PostgreSQL 15 connectivity and Hibernate schema generation"
    )
    void testDatabaseConnectivityAndSchema() throws Exception {
        try (
            Connection conn = dataSource.getConnection();
            Statement stmt = conn.createStatement()
        ) {
            ResultSet rs = stmt.executeQuery("SELECT version();");
            assertTrue(rs.next());
            String version = rs.getString(1);
            log.info("Connected to Real PostgreSQL: {}", version);
            assertTrue(
                version.contains("PostgreSQL 15"),
                "Expected PostgreSQL 15 but got: " + version
            );

            // Verify tables generated by Hibernate
            ResultSet tableRs = stmt.executeQuery(
                "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public';"
            );
            List<String> tables = new ArrayList<>();
            while (tableRs.next()) {
                tables.add(tableRs.getString(1).toLowerCase());
            }
            log.info("Verified Hibernate tables in PostgreSQL: {}", tables);
            assertTrue(tables.contains("users"), "Table 'users' must exist");
            assertTrue(
                tables.contains("game_sessions"),
                "Table 'game_sessions' must exist"
            );
            assertTrue(
                tables.contains("processed_game_events"),
                "Table 'processed_game_events' must exist"
            );
        }
    }

    @Test
    @Order(2)
    @DisplayName(
        "PG-02: User persistence, retrieval, and unique constraint enforcement"
    )
    void testUserPersistenceAndUniqueConstraints() {
        String uniqueSuffix = UUID.randomUUID().toString().substring(0, 8);
        String username = "pg_user_" + uniqueSuffix;

        UserEntity user = UserEntity.builder()
            .username(username)
            .password("hashedSecret123")
            .email(username + "@example.com")
            .eloRating(1200)
            .build();

        UserEntity saved = userRepository.save(user);
        assertTrue(saved.getId() > 0);

        UserEntity found = userRepository
            .findByUsername(username)
            .orElseThrow();
        assertEquals(username, found.getUsername());
        assertEquals(1200, found.getEloRating());

        // Duplicate username should throw DataIntegrityViolationException from PostgreSQL unique index
        UserEntity duplicate = UserEntity.builder()
            .username(username)
            .password("pass")
            .email("other_" + uniqueSuffix + "@example.com")
            .eloRating(1200)
            .build();

        assertThrows(DataIntegrityViolationException.class, () -> {
            userRepository.saveAndFlush(duplicate);
        });
    }

    @Test
    @Order(3)
    @DisplayName("PG-03: Transaction rollback consistency")
    void testTransactionRollback() {
        String rollbackUser =
            "rollback_user_" + UUID.randomUUID().toString().substring(0, 8);
        TransactionTemplate tx = new TransactionTemplate(transactionManager);

        assertThrows(RuntimeException.class, () -> {
            tx.execute(status -> {
                UserEntity u = UserEntity.builder()
                    .username(rollbackUser)
                    .password("pass")
                    .email(rollbackUser + "@example.com")
                    .eloRating(1200)
                    .build();
                userRepository.save(u);
                throw new RuntimeException("Simulated mid-transaction failure");
            });
        });

        assertTrue(
            userRepository.findByUsername(rollbackUser).isEmpty(),
            "Rolled back user must not exist"
        );
    }

    @Test
    @Order(4)
    @DisplayName(
        "PG-04: Atomic INSERT ... ON CONFLICT DO NOTHING against real PostgreSQL"
    )
    void testAtomicInsertOnConflictDoNothing() {
        UUID gameId = UUID.randomUUID();

        int firstInsert = processedEventRepository.insertIfNotExists(
            gameId,
            Instant.now()
        );
        assertEquals(1, firstInsert, "First insert must affect 1 row");

        int duplicateInsert = processedEventRepository.insertIfNotExists(
            gameId,
            Instant.now()
        );
        assertEquals(
            0,
            duplicateInsert,
            "Duplicate insert must affect 0 rows (ON CONFLICT DO NOTHING)"
        );

        assertTrue(processedEventRepository.findById(gameId).isPresent());
    }

    @Test
    @Order(5)
    @DisplayName(
        "PG-05: Concurrent duplicate GameEndedEvents on real PostgreSQL"
    )
    void testConcurrentDuplicateGameEndedEventsOnRealPostgres()
        throws Exception {
        UUID gameId = UUID.randomUUID();
        String winName = "pg_conc_win_" + gameId.toString().substring(0, 8);
        String loseName = "pg_conc_los_" + gameId.toString().substring(0, 8);

        UserEntity winner = UserEntity.builder()
            .username(winName)
            .password("p")
            .email(winName + "@x.com")
            .eloRating(1200)
            .build();
        userRepository.save(winner);

        UserEntity loser = UserEntity.builder()
            .username(loseName)
            .password("p")
            .email(loseName + "@x.com")
            .eloRating(1200)
            .build();
        userRepository.save(loser);

        GameSession session = GameSession.builder()
            .gameId(gameId)
            .gameType(GameType.CHESS)
            .status(GameStatus.IN_PROGRESS)
            .player1(Player.builder().username(winName).build())
            .player2(Player.builder().username(loseName).build())
            .build();
        gameStateRepository.save(session);

        GameEndedEvent event = new GameEndedEvent(
            gameId,
            winName,
            loseName,
            "CHECKMATE"
        );

        int threads = 8;
        ExecutorService executor = Executors.newFixedThreadPool(threads);
        CountDownLatch startLatch = new CountDownLatch(1);
        CountDownLatch doneLatch = new CountDownLatch(threads);
        AtomicInteger successCount = new AtomicInteger(0);

        for (int i = 0; i < threads; i++) {
            executor.submit(() -> {
                try {
                    startLatch.await();
                    gameEventConsumer.consumeGameEndedEvent(event);
                    successCount.incrementAndGet();
                } catch (Exception e) {
                    log.error("Concurrent delivery error", e);
                } finally {
                    doneLatch.countDown();
                }
            });
        }

        startLatch.countDown();
        assertTrue(doneLatch.await(10, TimeUnit.SECONDS));
        executor.shutdown();

        assertEquals(
            threads,
            successCount.get(),
            "All threads must finish cleanly without transaction failure"
        );

        UserEntity finalWinner = userRepository
            .findByUsername(winName)
            .orElseThrow();
        UserEntity finalLoser = userRepository
            .findByUsername(loseName)
            .orElseThrow();

        assertEquals(
            1216,
            finalWinner.getEloRating(),
            "Winner Elo must be exactly 1216 (only updated once)"
        );
        assertEquals(
            1184,
            finalLoser.getEloRating(),
            "Loser Elo must be exactly 1184 (only updated once)"
        );
        assertTrue(processedEventRepository.findById(gameId).isPresent());
    }

