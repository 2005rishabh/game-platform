    @Test
    @Order(6)
    @DisplayName(
        "PG-BENCH: PostgreSQL Throughput and Latency Benchmarks (User creation, lookup, Elo update, ProcessedEvent, Commit)"
    )
    void runPostgresPerformanceBenchmarks() throws Exception {
        log.info("Starting PostgreSQL Real Infrastructure Benchmark Suite...");

        // Warm up
        for (int i = 0; i < 50; i++) {
            UUID id = UUID.randomUUID();
            userRepository.save(
                UserEntity.builder()
                    .username("warmup_" + id)
                    .password("pass")
                    .email("w" + id + "@test.com")
                    .eloRating(1200)
                    .build()
            );
        }

        int[] workloads = { 10, 50, 100 };

        for (int concurrency : workloads) {
            log.info(
                "\n======================================================="
            );
            log.info(
                "RUNNING POSTGRESQL BENCHMARK AT CONCURRENCY: {}",
                concurrency
            );
            log.info("=======================================================");

            // 1. User Creation Benchmark
            BenchmarkResult userCreateResult = benchmarkTask(
                "User Creation",
                concurrency,
                concurrency * 20,
                () -> {
                    String u = "bench_u_" + UUID.randomUUID();
                    userRepository.save(
                        UserEntity.builder()
                            .username(u)
                            .password("pwd123")
                            .email(u + "@bench.com")
                            .eloRating(1200)
                            .build()
                    );
                    return null;
                }
            );

            // 2. User Lookup Latency Benchmark
            List<String> usernamesToLookup = new ArrayList<>();
            for (int i = 0; i < 100; i++) {
                String u =
                    "lookup_target_" +
                    UUID.randomUUID().toString().substring(0, 8);
                userRepository.save(
                    UserEntity.builder()
                        .username(u)
                        .password("pwd")
                        .email(u + "@t.com")
                        .eloRating(1200)
                        .build()
                );
                usernamesToLookup.add(u);
            }
            AtomicInteger lookupIdx = new AtomicInteger(0);
            BenchmarkResult userLookupResult = benchmarkTask(
                "User Lookup",
                concurrency,
                concurrency * 20,
                () -> {
                    String target = usernamesToLookup.get(
                        Math.abs(
                            lookupIdx.getAndIncrement() %
                                usernamesToLookup.size()
                        )
                    );
                    userRepository.findByUsername(target);
                    return null;
                }
            );

            // 3. Processed-Event Insertion Latency (Native INSERT ... ON CONFLICT DO NOTHING)
            BenchmarkResult processedEventResult = benchmarkTask(
                "ProcessedEvent Insertion",
                concurrency,
                concurrency * 20,
                () -> {
                    UUID gid = UUID.randomUUID();
                    processedEventRepository.insertIfNotExists(
                        gid,
                        Instant.now()
                    );
                    return null;
                }
            );

            // 4. Elo Update Latency Benchmark
            String eloUser =
                "elo_bench_" + UUID.randomUUID().toString().substring(0, 8);
            UserEntity userForElo = userRepository.save(
                UserEntity.builder()
                    .username(eloUser)
                    .password("p")
                    .email(eloUser + "@b.com")
                    .eloRating(1200)
                    .build()
            );
            Long eloUserId = userForElo.getId();

            BenchmarkResult eloUpdateResult = benchmarkTask(
                "Elo Rating Update",
                concurrency,
                concurrency * 20,
                () -> {
                    TransactionTemplate tx = new TransactionTemplate(
                        transactionManager
                    );
                    tx.execute(status -> {
                        UserEntity u = userRepository
                            .findById(eloUserId)
                            .orElseThrow();
                        u.setEloRating(u.getEloRating() + 1);
                        userRepository.save(u);
                        return null;
                    });
                    return null;
                }
            );

            // 5. Transaction Commit Latency Benchmark
            BenchmarkResult txCommitResult = benchmarkTask(
                "Transaction Commit",
                concurrency,
                concurrency * 20,
                () -> {
                    TransactionTemplate tx = new TransactionTemplate(
                        transactionManager
                    );
                    tx.setPropagationBehavior(
                        TransactionDefinition.PROPAGATION_REQUIRES_NEW
                    );
                    tx.execute(status -> {
                        processedEventRepository.insertIfNotExists(
                            UUID.randomUUID(),
                            Instant.now()
                        );
                        return null;
                    });
                    return null;
                }
            );

            // Pool utilization
            if (dataSource instanceof HikariDataSource hikariDs) {
                log.info(
                    "HikariCP Pool Utilization [Concurrency {}]: Active={}, Idle={}, Total={}, AwaitingThreads={}",
                    concurrency,
                    hikariDs.getHikariPoolMXBean().getActiveConnections(),
                    hikariDs.getHikariPoolMXBean().getIdleConnections(),
                    hikariDs.getHikariPoolMXBean().getTotalConnections(),
                    hikariDs
                        .getHikariPoolMXBean()
                        .getThreadsAwaitingConnection()
                );
            }

            printBenchmarkTable(
                concurrency,
                List.of(
                    userCreateResult,
                    userLookupResult,
                    processedEventResult,
                    eloUpdateResult,
                    txCommitResult
                )
            );
        }
    }

    private BenchmarkResult benchmarkTask(
        String taskName,
        int threads,
        int totalOps,
        Callable<Void> action
    ) throws Exception {
        ExecutorService executor = Executors.newFixedThreadPool(threads);
        CountDownLatch startLatch = new CountDownLatch(1);
        CountDownLatch doneLatch = new CountDownLatch(totalOps);
        List<Double> latencies = Collections.synchronizedList(
            new ArrayList<>(totalOps)
        );
        AtomicInteger failures = new AtomicInteger(0);

        long startNs = System.nanoTime();
        for (int i = 0; i < totalOps; i++) {
            executor.submit(() -> {
                try {
                    startLatch.await();
                    long t0 = System.nanoTime();
                    action.call();
                    long t1 = System.nanoTime();
                    latencies.add((t1 - t0) / 1_000_000.0); // ms
                } catch (Exception e) {
                    failures.incrementAndGet();
                } finally {
                    doneLatch.countDown();
                }
            });
        }

        startLatch.countDown();
        doneLatch.await(30, TimeUnit.SECONDS);
        long endNs = System.nanoTime();
        executor.shutdown();

        double totalTimeSec = (endNs - startNs) / 1_000_000_000.0;
        double throughput = (totalOps - failures.get()) / totalTimeSec;

        Collections.sort(latencies);
        double avg = latencies
            .stream()
            .mapToDouble(Double::doubleValue)
            .average()
            .orElse(0.0);
        double p50 = latencies.isEmpty()
            ? 0
            : latencies.get((int) (latencies.size() * 0.50));
        double p95 = latencies.isEmpty()
            ? 0
            : latencies.get((int) (latencies.size() * 0.95));
        double p99 = latencies.isEmpty()
            ? 0
            : latencies.get((int) (latencies.size() * 0.99));
        double failureRate = (failures.get() * 100.0) / totalOps;

        return new BenchmarkResult(
            taskName,
            threads,
            totalOps,
            throughput,
            avg,
            p50,
            p95,
            p99,
            failureRate
        );
    }

    private void printBenchmarkTable(
        int concurrency,
        List<BenchmarkResult> results
    ) {
        System.out.println(
            "\n----------------------------------------------------------------------------------------------------------------"
        );
        System.out.printf(
            "POSTGRESQL BENCHMARK REPORT (Concurrency: %d)%n",
            concurrency
        );
        System.out.println(
            "----------------------------------------------------------------------------------------------------------------"
        );
        System.out.printf(
            "%-26s | %-12s | %-10s | %-10s | %-10s | %-10s | %-10s%n",
            "Operation",
            "Throughput",
            "Avg Latency",
            "p50 Latency",
            "p95 Latency",
            "p99 Latency",
            "Fail Rate"
        );
        System.out.println(
            "---------------------------|--------------|------------|-------------|-------------|-------------|-----------"
        );
        for (BenchmarkResult r : results) {
            System.out.printf(
                "%-26s | %9.1f ops/s | %7.2f ms | %8.2f ms | %8.2f ms | %8.2f ms | %8.1f%%%n",
                r.name,
                r.throughput,
                r.avgMs,
                r.p50Ms,
                r.p95Ms,
                r.p99Ms,
                r.failureRate
            );
        }
        System.out.println(
            "----------------------------------------------------------------------------------------------------------------\n"
        );
    }

    public record BenchmarkResult(
        String name,
        int concurrency,
        int totalOps,
        double throughput,
        double avgMs,
        double p50Ms,
        double p95Ms,
        double p99Ms,
        double failureRate
    ) {}
